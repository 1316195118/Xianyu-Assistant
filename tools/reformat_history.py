def build_changelog(history):
    """从 history 重新生成整篇 CHANGELOG（最新在最上）。"""
    parts = [V.CHANGELOG_HEADER]
    for e in reversed(history):
        block = f"## {e['version']} · {e['time']}\n\n{e.get('note') or V.DEFAULT_NOTE}\n\n"
        if e.get('build'):
            block += f"前端构建：`{e['build']}`\n\n"
        parts.append(block + '---\n\n')
    return ''.join(parts)


def main():
    check_only = '--check' in sys.argv
    hist_path = os.path.join(V.VERSION_DIR, V.HISTORY)
    with open(hist_path, encoding='utf-8') as f:
        history = json.load(f)

    missing = [e['version'] for e in history if e['version'] not in NOTES]
    if missing:
        print('缺少整理结果的版本：', ', '.join(missing))
        return 1

    changed = 0
    for e in history:
        note = NOTES[e['version']].strip()
        if e.get('note') != note:
            e['note'] = note
            changed += 1

    if check_only:
        print(f'待整理 {changed}/{len(history)} 条（未写入）')
        return 0

    V.atomic_write(hist_path, json.dumps(history, ensure_ascii=False, indent=2) + '\n')
    V.atomic_write(os.path.join(V.VERSION_DIR, V.CHANGELOG), build_changelog(history))

    state = V.read_state()
    V.generate_go(state['version'], state['count'], state['updated_at'],
                  state.get('note', ''), history, state.get('build', ''))
    print(f'已整理 {changed}/{len(history)} 条说明，CHANGELOG 与 version_gen.go 已重建')
    return 0


if __name__ == '__main__':
    sys.exit(main())
